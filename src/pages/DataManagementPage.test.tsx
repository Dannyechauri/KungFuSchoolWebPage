import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { AuthContext } from '../features/auth/authContext'
import { DataManagementPage } from './DataManagementPage'

const fetchMock = vi.fn()
type Row = Record<string, unknown>
type Column = {
  name: string
  primaryKey: boolean
  dataType: string
  nullable: boolean
  autoGenerated: boolean
  hasDefault: boolean
  foreignKey: { tableName: string; columnName: string } | null
}
type Write = { table: string; method: string; payload: Row; id?: string }

function jsonResponse(body: unknown, status = 200) {
  return { ok: status >= 200 && status < 300, status, json: async () => body }
}

function installApi(tables: string[], columns: Record<string, Column[]>, rows: Record<string, Row[]>, hiddenRows: Record<string, Row[]> = {}) {
  const writes: Write[] = []
  fetchMock.mockImplementation(async (input: string, init?: RequestInit) => {
    const url = String(input)
    if (url.endsWith('/api/database/tables')) return jsonResponse(tables)
    const knownFormsMatch = /\/api\/database\/students\/(\d+)\/known-forms$/u.exec(url)
    if (knownFormsMatch) {
      const knownForms = (rows.alumno_forma ?? [])
        .filter((row) => String(row.id_alumno) === knownFormsMatch[1])
        .map((row) => {
          const form = rows.formas?.find((candidate) => String(candidate.id_forma) === String(row.id_forma))
          const style = rows.estilos?.find((candidate) => String(candidate.id_estilo) === String(form?.id_estilo))
          return { ...row, nombre: form?.nombre, descripcion: form?.descripcion ?? null, estilo: style?.nombre }
        })
      return jsonResponse(knownForms)
    }
    const match = /\/api\/database\/tables\/([^/]+)\/(columns|rows)(?:\/([^/?]+))?(?:\?[^/]*)?$/u.exec(url)
    if (!match) throw new Error(`Ruta inesperada: ${url}`)
    const table = decodeURIComponent(match[1] ?? '')
    const operation = match[2]
    const id = match[3] ? decodeURIComponent(match[3]) : undefined
    if (operation === 'columns') return jsonResponse(columns[table] ?? [])

    const method = init?.method ?? 'GET'
    if (method === 'POST') {
      const payload = JSON.parse(String(init?.body)) as Row
      const keyColumns = (columns[table] ?? []).filter((column) => column.primaryKey)
      const existing = (rows[table] ?? []).find((row) => keyColumns.length > 0
        && keyColumns.every((column) => String(row[column.name]) === String(payload[column.name])))
      const saved = existing ?? payload
      if (!existing) rows[table] = [...(rows[table] ?? []), payload]
      writes.push({ table, method, payload })
      return jsonResponse(saved, 201)
    }
    if (method === 'PUT' && id) {
      const payload = JSON.parse(String(init?.body)) as Row
      const keyColumns = (columns[table] ?? []).filter((column) => column.primaryKey)
      const keyValues = id.split(',')
      const rowIndex = (rows[table] ?? []).findIndex((row) => keyColumns.every((column, index) => String(row[column.name]) === keyValues[index]))
      if (rowIndex >= 0) rows[table]![rowIndex] = { ...rows[table]![rowIndex], ...payload }
      writes.push({ table, method, payload, id })
      return jsonResponse(rows[table]?.[rowIndex] ?? payload)
    }
    if (method === 'DELETE' && id) {
      const keyColumns = (columns[table] ?? []).filter((column) => column.primaryKey)
      const keyValues = id.split(',')
      rows[table] = (rows[table] ?? []).filter((row) => !keyColumns.every((column, index) => String(row[column.name]) === keyValues[index]))
      writes.push({ table, method, payload: {}, id })
      return jsonResponse({ deleted: true })
    }
    return jsonResponse((rows[table] ?? []).filter((row) => !hiddenRows[table]?.some((hidden) =>
      Object.entries(hidden).every(([key, value]) => String(row[key]) === String(value)))))
  })
  vi.stubGlobal('fetch', fetchMock)
  return writes
}

function renderAdminPage() {
  return render(
    <AuthContext.Provider value={{
      user: { authenticated: true, role: 'ADMIN', userId: 1, displayName: 'Administración' },
      isCheckingSession: false,
      login: async () => undefined,
      logout: async () => undefined,
    }}>
      <DataManagementPage />
    </AuthContext.Provider>,
  )
}

const textColumn = (name: string, primaryKey = false): Column => ({
  name,
  primaryKey,
  dataType: 'text',
  nullable: !primaryKey,
  autoGenerated: false,
  hasDefault: false,
  foreignKey: null,
})

afterEach(() => {
  cleanup()
  vi.unstubAllGlobals()
})

describe('gestión amigable de datos', () => {
  it('oculta tablas de relación en modo amigable y las conserva en la vista amplia', async () => {
    installApi(
      ['alumnos', 'formas', 'instructores', 'alumno_forma', 'grado_forma', 'instructor_estilo'],
      { alumnos: [textColumn('id_alumno', true), textColumn('nombre')] },
      { alumnos: [{ id_alumno: 7, nombre: 'Ana Sol' }] },
    )
    const user = userEvent.setup()
    renderAdminPage()
    expect(await screen.findByRole('heading', { name: 'Ana Sol' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Formación' }))
    expect(screen.getByRole('button', { name: 'Formas' })).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Alumno · formas' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Grados · formas' })).toBeNull()
    expect(screen.queryByRole('button', { name: 'Instructor · estilos' })).toBeNull()

    await user.click(screen.getByRole('checkbox', { name: 'Vista amigable' }))
    expect(screen.getByRole('table')).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Alumno · formas' })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Grados · formas' })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Instructor · estilos' })).toBeTruthy()
  })

  it('muestra formas conocidas y las del grado dentro de la ficha del alumno', async () => {
    const writes = installApi(
      ['alumnos', 'grados', 'formas', 'estilos', 'alumno_forma', 'grado_forma'],
      {
        alumnos: [
          { ...textColumn('id_alumno', true), dataType: 'bigint', nullable: false, autoGenerated: true, hasDefault: true, foreignKey: null },
          { ...textColumn('nombre'), dataType: 'text', nullable: false, autoGenerated: false, hasDefault: false, foreignKey: null },
          { ...textColumn('id_grado'), dataType: 'bigint', nullable: false, autoGenerated: false, hasDefault: false, foreignKey: { tableName: 'grados', columnName: 'id_grado' } },
          { ...textColumn('es_instructor'), dataType: 'boolean', nullable: false, autoGenerated: false, hasDefault: true, foreignKey: null },
        ],
        grados: [{ ...textColumn('id_grado', true), dataType: 'bigint' }, { ...textColumn('nombre'), dataType: 'text' }],
        alumno_forma: [textColumn('id_alumno', true), textColumn('id_forma', true), textColumn('fecha_aprendida')],
        grado_forma: [textColumn('id_grado', true), textColumn('id_forma', true), textColumn('es_opcional')],
      },
      {
        alumnos: [{ id_alumno: 7, nombre: 'Ana Sol', id_grado: 4, es_instructor: false }],
        grados: [{ id_grado: 4, nombre: 'Cinta Verde' }],
        alumno_forma: [
          { id_alumno: 7, id_forma: 1, fecha_aprendida: '2025-03-01' },
          { id_alumno: 7, id_forma: 2, fecha_aprendida: '2025-02-01' },
        ],
        grado_forma: [{ id_grado: 4, id_forma: 1, es_opcional: false }, { id_grado: 4, id_forma: 2, es_opcional: true }],
        formas: [
          { id_forma: 1, id_estilo: 9, nombre: 'Forma Base' },
          { id_forma: 2, id_estilo: 9, nombre: 'Forma Avanzada' },
          { id_forma: 3, id_estilo: 9, nombre: 'Forma Libre' },
        ],
        estilos: [{ id_estilo: 9, nombre: 'Shaolin' }],
      },
      { alumno_forma: [{ id_alumno: 7, id_forma: 2 }] },
    )
    const user = userEvent.setup()
    renderAdminPage()

    await user.click(await screen.findByRole('button', { name: 'Editar Ana Sol' }))
    expect(await screen.findByRole('heading', { name: 'Formación del alumno' })).toBeTruthy()
    expect(screen.getByText('Forma Base')).toBeTruthy()
    expect(screen.getByText('Forma Avanzada')).toBeTruthy()
    expect(screen.getByText(/· Opcional/)).toBeTruthy()
    expect(screen.getByText('Sabida · 01/03/2025')).toBeTruthy()
    expect(screen.getByText('2 sabidas')).toBeTruthy()
    expect(screen.getByText('Sabida · 01/02/2025')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Quitar como sabida: Forma Avanzada' }))
    expect(writes).toContainEqual(expect.objectContaining({ table: 'alumno_forma', method: 'DELETE', id: '7,2' }))
    await waitFor(() => {
      const gradeFormsSection = screen.getByRole('heading', { name: 'Formas según su grado' }).parentElement!.parentElement!
      expect(within(gradeFormsSection).getByText('Sabida · 01/03/2025')).toBeTruthy()
      expect(within(gradeFormsSection).getByRole('button', { name: 'Marcar como sabida: Forma Avanzada' })).toBeTruthy()
      expect(within(gradeFormsSection).getByText(/1\s+sabida/u)).toBeTruthy()
    })
    await user.click(screen.getByRole('button', { name: 'Marcar como sabida: Forma Avanzada' }))
    expect(writes).toContainEqual(expect.objectContaining({
      table: 'alumno_forma',
      method: 'POST',
      payload: expect.objectContaining({ id_alumno: '7', id_forma: '2', fecha_aprendida: expect.stringMatching(/^\d{4}-\d{2}-\d{2}$/u) }),
    }))
    await waitFor(() => {
      const gradeFormsSection = screen.getByRole('heading', { name: 'Formas según su grado' }).parentElement!.parentElement!
      expect(within(gradeFormsSection).getAllByText(/^Sabida · \d{2}\/\d{2}\/\d{4}$/u)).toHaveLength(2)
      expect(within(gradeFormsSection).getByText('2 sabidas')).toBeTruthy()
    })

    const baseFormDate = screen.getByLabelText('Fecha aprendida de Forma Base')
    fireEvent.change(baseFormDate, { target: { value: '2025-03-02' } })
    await user.click(screen.getByRole('button', { name: 'Guardar' }))
    expect(writes).toContainEqual(expect.objectContaining({ table: 'alumnos', method: 'PUT' }))
    expect(writes).toContainEqual(expect.objectContaining({
      table: 'alumno_forma',
      method: 'PUT',
      payload: { fecha_aprendida: '2025-03-02' },
    }))
    await waitFor(() => expect(screen.queryByRole('heading', { name: 'Editar registro' })).toBeNull())
    await user.click(screen.getByRole('button', { name: 'Editar Ana Sol' }))
    expect(await screen.findByRole('heading', { name: 'Formación del alumno' })).toBeTruthy()

    await user.selectOptions(screen.getByLabelText('Añadir forma sabida'), '3')
    await user.click(screen.getByRole('button', { name: 'Añadir' }))
    expect(writes).toContainEqual(expect.objectContaining({
      table: 'alumno_forma',
      method: 'POST',
      payload: expect.objectContaining({ id_alumno: '7', id_forma: '3' }),
    }))
  })

  it('permite configurar formas obligatorias y opcionales dentro de un grado', async () => {
    const writes = installApi(
      ['grados', 'formas', 'estilos', 'grado_forma'],
      {
        grados: [textColumn('id_grado', true), textColumn('nombre')],
        grado_forma: [textColumn('id_grado', true), textColumn('id_forma', true), textColumn('es_opcional')],
      },
      {
        grados: [{ id_grado: 4, nombre: 'Cinta Verde' }],
        grado_forma: [{ id_grado: 4, id_forma: 1, es_opcional: false }],
        formas: [{ id_forma: 1, id_estilo: 9, nombre: 'Forma Base' }, { id_forma: 2, id_estilo: 9, nombre: 'Forma Avanzada' }],
        estilos: [{ id_estilo: 9, nombre: 'Shaolin' }],
      },
    )
    const user = userEvent.setup()
    renderAdminPage()

    await user.click(await screen.findByRole('button', { name: 'Editar Cinta Verde' }))
    expect(await screen.findByRole('heading', { name: 'Formas de este grado' })).toBeTruthy()
    const optionalCheckbox = screen.getAllByRole('checkbox', { name: 'Opcional' })[0]!
    await user.click(optionalCheckbox)
    expect(writes).toContainEqual(expect.objectContaining({ table: 'grado_forma', method: 'PUT', payload: { es_opcional: true } }))

    expect(await screen.findByLabelText('Añadir forma al grado')).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Añadir forma al grado'), '2')
    await user.click(screen.getByRole('button', { name: 'Añadir' }))
    expect(writes).toContainEqual(expect.objectContaining({
      table: 'grado_forma',
      method: 'POST',
      payload: expect.objectContaining({ id_grado: '4', id_forma: '2', es_opcional: false }),
    }))
  })

  it('permite asignar estilos dentro de la ficha del instructor', async () => {
    const writes = installApi(
      ['instructores', 'estilos', 'instructor_estilo'],
      {
        instructores: [textColumn('id_instructor', true), textColumn('nombre')],
        instructor_estilo: [textColumn('id_instructor', true), textColumn('id_estilo', true)],
      },
      {
        instructores: [{ id_instructor: 12, nombre: 'Chen Wei' }],
        instructor_estilo: [{ id_instructor: 12, id_estilo: 9 }],
        estilos: [{ id_estilo: 9, nombre: 'Shaolin' }, { id_estilo: 10, nombre: 'Ving Tsun' }],
      },
    )
    const user = userEvent.setup()
    renderAdminPage()

    await user.click(await screen.findByRole('button', { name: 'Editar Chen Wei' }))
    expect(await screen.findByRole('heading', { name: 'Estilos del instructor' })).toBeTruthy()
    const details = screen.getByRole('region', { name: 'Formación y relaciones' })
    expect(within(details).getByText('Shaolin')).toBeTruthy()
    await user.selectOptions(within(details).getByLabelText('Añadir estilo'), '10')
    await user.click(within(details).getByRole('button', { name: 'Añadir estilo' }))
    expect(writes).toContainEqual(expect.objectContaining({
      table: 'instructor_estilo',
      method: 'POST',
      payload: expect.objectContaining({ id_instructor: '12', id_estilo: '10' }),
    }))
  })
})