import type { FormEvent } from 'react'
import { useEffect, useState } from 'react'
import { apiRequest } from '../api/client'
import { PanelCard } from '../components/PanelCard'
import { useAuth } from '../features/auth/useAuth'

type Column = { name: string; dataType: string; nullable: boolean; primaryKey: boolean; autoGenerated: boolean }
type Row = Record<string, unknown>

const tables = [
  ['cursos', 'Cursos'],
  ['instructores', 'Instructores'],
  ['alumnos', 'Alumnos'],
  ['estilos', 'Estilos'],
  ['formas', 'Formas'],
  ['grados', 'Grados'],
] as const

function isNumber(column: Column) {
  return ['smallint', 'integer', 'bigint', 'real', 'double precision', 'numeric', 'decimal'].includes(column.dataType)
}

function formatValue(value: unknown) {
  if (value === null || value === undefined || value === '') return '—'
  if (typeof value === 'boolean') return value ? 'Sí' : 'No'
  return String(value)
}

export function DataManagementPage() {
  const { user } = useAuth()
  const [table, setTable] = useState<(typeof tables)[number][0]>('cursos')
  const [columns, setColumns] = useState<Column[]>([])
  const [rows, setRows] = useState<Row[]>([])
  const [editingRow, setEditingRow] = useState<Row | null>(null)
  const [isCreating, setIsCreating] = useState(false)
  const [isLoading, setIsLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [reloadVersion, setReloadVersion] = useState(0)

  useEffect(() => {
    let active = true
    async function synchronizeData() {
      try {
        const [loadedColumns, loadedRows] = await Promise.all([
          apiRequest<Column[]>(`/api/database/tables/${table}/columns`),
          apiRequest<Row[]>(`/api/database/tables/${table}/rows?limit=500`),
        ])
        if (!active) return
        setColumns(loadedColumns)
        setRows(loadedRows)
        setError(null)
      } catch (loadError) {
        if (active) setError(loadError instanceof Error ? loadError.message : 'No se pudieron cargar los datos.')
      } finally {
        if (active) setIsLoading(false)
      }
    }
    void synchronizeData()
    return () => { active = false }
  }, [reloadVersion, table])

  async function saveRow(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    const formData = new FormData(event.currentTarget)
    const payload: Record<string, unknown> = {}
    for (const column of columns) {
      if (column.autoGenerated || column.primaryKey) continue
      const value = formData.get(column.name)
      if (column.name === 'password_hash' && !value) continue
      if (column.dataType === 'boolean') payload[column.name] = value === 'on'
      else if (value === '' && column.nullable) payload[column.name] = null
      else if (isNumber(column)) payload[column.name] = Number(value)
      else payload[column.name] = value
    }

    try {
      const primaryKey = columns.find((column) => column.primaryKey)
      if (editingRow && primaryKey) {
        await apiRequest(`/api/database/tables/${table}/rows/${editingRow[primaryKey.name]}`, { method: 'PUT', body: JSON.stringify(payload) })
      } else {
        await apiRequest(`/api/database/tables/${table}/rows`, { method: 'POST', body: JSON.stringify(payload) })
      }
      setEditingRow(null)
      setIsCreating(false)
      setIsLoading(true)
      setReloadVersion((version) => version + 1)
    } catch (saveError) {
      setError(saveError instanceof Error ? saveError.message : 'No se pudieron guardar los cambios.')
    }
  }

  async function deleteRow(row: Row) {
    const primaryKey = columns.find((column) => column.primaryKey)
    if (!primaryKey || !window.confirm('¿Eliminar este registro?')) return
    try {
      await apiRequest(`/api/database/tables/${table}/rows/${row[primaryKey.name]}`, { method: 'DELETE' })
      setIsLoading(true)
      setReloadVersion((version) => version + 1)
    } catch (deleteError) {
      setError(deleteError instanceof Error ? deleteError.message : 'No se pudo eliminar el registro.')
    }
  }

  const editableColumns = columns.filter((column) => !column.autoGenerated && !column.primaryKey)
  const visibleColumns = columns.filter((column) => column.name !== 'password_hash').slice(0, 6)
  const title = tables.find(([name]) => name === table)?.[1]

  if (user?.role !== 'ADMIN') return <section className="w-full text-muted">Esta sección requiere permisos de administración.</section>

  return (
    <section className="w-full">
      <p className="mb-2 text-xs font-black tracking-[0.12em] text-red uppercase">Gestión provisional</p>
      <h1 className="m-0 text-4xl font-bold tracking-tight text-ink md:text-5xl">Datos de la escuela</h1>
      <p className="mt-4 max-w-3xl text-base leading-7 text-muted">Herramienta temporal para añadir, editar y borrar la información necesaria durante la prueba.</p>

      <div className="mt-7 flex flex-wrap gap-2">
        {tables.map(([name, label]) => <button key={name} className={`rounded-full px-4 py-2 text-sm font-bold ${table === name ? 'bg-red text-white' : 'border border-line bg-paper text-muted'}`} type="button" onClick={() => { setIsLoading(true); setTable(name); setEditingRow(null); setIsCreating(false) }}>{label}</button>)}
      </div>

      <div className="mt-5 flex items-center justify-between gap-4">
        <h2 className="m-0 text-2xl font-bold text-ink">{title}</h2>
        <button className="rounded-full bg-red px-4 py-2 text-sm font-bold text-white" type="button" onClick={() => { setEditingRow(null); setIsCreating(true) }}>+ Añadir</button>
      </div>

      {error ? <p className="mt-4 rounded-soft bg-red/10 p-3 text-sm font-bold text-red-dark">{error}</p> : null}

      {isCreating || editingRow ? (
        <PanelCard className="mt-5 p-6">
          <h3 className="m-0 text-xl font-bold text-ink">{editingRow ? 'Editar registro' : 'Nuevo registro'}</h3>
          <form className="mt-5 grid gap-4 md:grid-cols-2 xl:grid-cols-3" onSubmit={saveRow}>
            {editableColumns.map((column) => {
              const currentValue = editingRow?.[column.name]
              const inputType = column.name === 'password_hash' ? 'password' : column.dataType === 'date' ? 'date' : column.dataType.includes('timestamp') ? 'datetime-local' : isNumber(column) ? 'number' : 'text'
              if (column.dataType === 'boolean') {
                return <label key={column.name} className="flex items-center gap-3 text-sm font-bold text-muted"><input name={column.name} type="checkbox" defaultChecked={currentValue !== false} />{column.name}</label>
              }
              return <label key={column.name} className="grid gap-2 text-sm font-bold text-muted">{column.name}<input className="min-h-11 rounded-soft border border-line bg-white px-3 text-ink" name={column.name} type={inputType} defaultValue={currentValue ? String(currentValue).slice(0, inputType === 'datetime-local' ? 16 : undefined) : ''} required={!column.nullable && column.name !== 'password_hash'} /></label>
            })}
            <div className="md:col-span-2 xl:col-span-3 flex gap-3"><button className="rounded-full bg-red px-5 py-2 text-sm font-bold text-white" type="submit">Guardar</button><button className="rounded-full border border-line bg-paper px-5 py-2 text-sm font-bold text-muted" type="button" onClick={() => { setEditingRow(null); setIsCreating(false) }}>Cancelar</button></div>
          </form>
        </PanelCard>
      ) : null}

      <PanelCard className="mt-5 overflow-x-auto p-5">
        {isLoading ? <p className="text-muted">Cargando datos…</p> : (
          <table className="w-full min-w-[44rem] border-collapse text-left text-sm"><thead><tr className="border-b border-line text-muted">{visibleColumns.map((column) => <th key={column.name} className="p-3 font-bold">{column.name}</th>)}<th className="p-3">Acciones</th></tr></thead><tbody>{rows.map((row) => <tr key={String(row[columns.find((column) => column.primaryKey)?.name ?? 'id'])} className="border-b border-line/70"><>{visibleColumns.map((column) => <td key={column.name} className="max-w-56 truncate p-3 text-ink">{formatValue(row[column.name])}</td>)}</><td className="whitespace-nowrap p-3"><button className="mr-3 font-bold text-red-dark" type="button" onClick={() => { setEditingRow(row); setIsCreating(false) }}>Editar</button><button className="font-bold text-red" type="button" onClick={() => void deleteRow(row)}>Borrar</button></td></tr>)}</tbody></table>
        )}
      </PanelCard>
    </section>
  )
}
