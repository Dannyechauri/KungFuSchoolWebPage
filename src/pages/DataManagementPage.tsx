import type { FormEvent } from 'react'
import { useEffect, useMemo, useState } from 'react'
import { apiRequest } from '../api/client'
import { PanelCard } from '../components/PanelCard'
import { SelectField } from '../components/SelectField'
import { useAuth } from '../features/auth/useAuth'

type ForeignKey = { tableName: string; columnName: string }
type Column = {
  name: string
  dataType: string
  nullable: boolean
  primaryKey: boolean
  autoGenerated: boolean
  hasDefault: boolean
  foreignKey: ForeignKey | null
}
type Row = Record<string, unknown>
type ReferencedTable = { columns: Column[]; rows: Row[] }

const tableLabels: Record<string, string> = {
  administradores: 'Administradores',
  alumno_forma: 'Alumno · formas',
  alumno_grado: 'Alumno · grados',
  alumnos: 'Alumnos',
  asistencias_curso: 'Asistencias',
  cursos: 'Cursos',
  cursos_agendados: 'Sesiones de cursos',
  estilos: 'Estilos',
  formas: 'Formas',
  grado_forma: 'Grados · formas',
  grados: 'Grados',
  horarios_recurrentes: 'Horarios habituales',
  inscripciones: 'Inscripciones',
  instructor_estilo: 'Instructor · estilos',
  instructores: 'Instructores',
  personas: 'Personas',
  salas: 'Salas',
  usuarios: 'Usuarios',
}

const inputClass = 'min-h-11 w-full rounded-soft border border-line bg-white px-3 text-ink'

function tableLabel(table: string) {
  return tableLabels[table] ?? table.replaceAll('_', ' ').replace(/^\p{L}/u, (letter) => letter.toLocaleUpperCase('es-ES'))
}

function isNumber(column: Column) {
  return ['smallint', 'integer', 'bigint', 'real', 'double precision', 'numeric', 'decimal'].includes(column.dataType)
}

function formatValue(value: unknown) {
  if (value === null || value === undefined || value === '') return '—'
  if (typeof value === 'boolean') return value ? 'Sí' : 'No'
  return String(value)
}

function primaryKeyColumns(columns: Column[]) {
  return columns.filter((column) => column.primaryKey)
}

function rowId(row: Row, columns: Column[]) {
  return primaryKeyColumns(columns).map((column) => String(row[column.name])).join(',')
}

function referenceLabel(row: Row, reference: ForeignKey, columns: Column[]) {
  const value = row[reference.columnName]
  const labelColumn = columns.find((column) => column.name === 'nombre')
    ?? columns.find((column) => ['correo_electronico', 'numero_matricula', 'fecha_hora'].includes(column.name))
    ?? columns.find((column) => !column.primaryKey && column.name !== 'password_hash')
  const label = labelColumn ? formatValue(row[labelColumn.name]) : `ID ${formatValue(value)}`
  return labelColumn && labelColumn.name !== reference.columnName ? `${label} · ${formatValue(value)}` : label
}

function removalLabel(table: string) {
  if (table === 'cursos_agendados') return 'Cancelar sesión'
  if (table === 'horarios_recurrentes') return 'Cancelar horario'
  if (table === 'salas') return 'Desactivar'
  return 'Eliminar'
}

export function DataManagementPage() {
  const { user } = useAuth()
  const isAdmin = user?.role === 'ADMIN'
  const [tables, setTables] = useState<string[]>([])
  const [table, setTable] = useState('')
  const [columns, setColumns] = useState<Column[]>([])
  const [rows, setRows] = useState<Row[]>([])
  const [referencedTables, setReferencedTables] = useState<{ owner: string; values: Record<string, ReferencedTable> }>({ owner: '', values: {} })
  const [editingRow, setEditingRow] = useState<Row | null>(null)
  const [isCreating, setIsCreating] = useState(false)
  const [isTableListLoading, setIsTableListLoading] = useState(true)
  const [tableListVersion, setTableListVersion] = useState(0)
  const [isLoading, setIsLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [tableListError, setTableListError] = useState<string | null>(null)
  const [referenceError, setReferenceError] = useState<string | null>(null)
  const [reloadVersion, setReloadVersion] = useState(0)
  const [isSaving, setIsSaving] = useState(false)

  useEffect(() => {
    let active = true
    if (!isAdmin) return () => { active = false }
    apiRequest<string[]>('/api/database/tables')
      .then((loadedTables) => {
        if (!active) return
        setTables(loadedTables)
        setTable((current) => current && loadedTables.includes(current) ? current : loadedTables.includes('cursos') ? 'cursos' : loadedTables[0] ?? '')
        setTableListError(null)
      })
      .catch((loadError: unknown) => { if (active) setTableListError(loadError instanceof Error ? loadError.message : 'No se pudieron cargar las tablas.') })
      .finally(() => { if (active) setIsTableListLoading(false) })
    return () => { active = false }
  }, [isAdmin, tableListVersion])

  useEffect(() => {
    let active = true
    if (!isAdmin || !table) return () => { active = false }
    Promise.all([
      apiRequest<Column[]>(`/api/database/tables/${encodeURIComponent(table)}/columns`),
      apiRequest<Row[]>(`/api/database/tables/${encodeURIComponent(table)}/rows?limit=500`),
    ])
      .then(([loadedColumns, loadedRows]) => {
        if (!active) return
        setColumns(loadedColumns)
        setRows(loadedRows)
        setReferenceError(null)
        setError(null)
      })
      .catch((loadError: unknown) => { if (active) setError(loadError instanceof Error ? loadError.message : 'No se pudieron cargar el esquema y los registros.') })
      .finally(() => { if (active) setIsLoading(false) })
    return () => { active = false }
  }, [isAdmin, reloadVersion, table])

  const foreignKeyTables = useMemo(() => [...new Set(columns.flatMap((column) => column.foreignKey ? [column.foreignKey.tableName] : []))], [columns])
  const referenceOptionsLoading = foreignKeyTables.length > 0 && referencedTables.owner !== table && !referenceError
  useEffect(() => {
    let active = true
    if (!isAdmin || !table || !foreignKeyTables.length) return () => { active = false }
    Promise.all(foreignKeyTables.map(async (referencedTable) => {
      const [referencedColumns, referencedRows] = await Promise.all([
        apiRequest<Column[]>(`/api/database/tables/${encodeURIComponent(referencedTable)}/columns`),
        apiRequest<Row[]>(`/api/database/tables/${encodeURIComponent(referencedTable)}/rows?limit=500`),
      ])
      return [referencedTable, { columns: referencedColumns, rows: referencedRows }] as const
    }))
      .then((entries) => {
        if (active) {
          setReferencedTables({ owner: table, values: Object.fromEntries(entries) })
          setReferenceError(null)
        }
      })
      .catch((loadError: unknown) => { if (active) setReferenceError(loadError instanceof Error ? loadError.message : 'No se pudieron cargar las opciones relacionadas.') })
    return () => { active = false }
  }, [foreignKeyTables, isAdmin, reloadVersion, table])

  const references = referencedTables.owner === table ? referencedTables.values : {}
  const isAdministratorTable = table === 'administradores'
  const editableColumns = columns.filter((column) => !column.autoGenerated
    && (isCreating || !column.primaryKey)
    && !(column.name === 'password_hash' && !isCreating)
    && !(['cursos_agendados', 'horarios_recurrentes'].includes(table) && column.name === 'activo'))
  const visibleColumns = columns.filter((column) => column.name !== 'password_hash').slice(0, 6)
  const title = table ? tableLabel(table) : ''
  const hasPrimaryKey = primaryKeyColumns(columns).length > 0

  async function saveRow(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    const form = event.currentTarget
    const formData = new FormData(form)
    const payload: Record<string, unknown> = {}
    for (const column of editableColumns) {
      const value = formData.get(column.name)
      if (column.name === 'password_hash' && !value) continue
      if (column.dataType === 'boolean') payload[column.name] = value === 'on'
      else if (value === '' && column.nullable) payload[column.name] = null
      else if (isNumber(column) && column.dataType !== 'bigint' && !column.foreignKey) payload[column.name] = Number(value)
      else payload[column.name] = value
    }

    if (table === 'cursos_agendados') {
      const startDate = String(payload.fecha_hora ?? '').slice(0, 10)
      const endDate = String(payload.fecha_hora_fin ?? '').slice(0, 10)
      if (startDate && endDate && startDate !== endDate) {
        setError('Cada registro de agenda debe ser una sesión de un solo día. Añade otra sesión para el siguiente día y reutiliza el mismo curso.')
        return
      }
    }

    setIsSaving(true)
    setError(null)
    try {
      const keys = primaryKeyColumns(columns)
      if (editingRow && keys.length) {
        const id = encodeURIComponent(rowId(editingRow, columns))
        await apiRequest(`/api/database/tables/${encodeURIComponent(table)}/rows/${id}`, { method: 'PUT', body: JSON.stringify(payload) })
      } else {
        await apiRequest(`/api/database/tables/${encodeURIComponent(table)}/rows`, { method: 'POST', body: JSON.stringify(payload) })
      }
      form.reset()
      setEditingRow(null)
      setIsCreating(false)
      setIsLoading(true)
      setReloadVersion((version) => version + 1)
    } catch (saveError) {
      setError(saveError instanceof Error ? saveError.message : 'No se pudieron guardar los cambios.')
    } finally {
      setIsSaving(false)
    }
  }

  async function deleteRow(row: Row) {
    const keys = primaryKeyColumns(columns)
    if (!keys.length) return
    const action = removalLabel(table)
    if (!window.confirm(`¿${action} este registro de ${title}?`)) return
    try {
      const id = encodeURIComponent(rowId(row, columns))
      await apiRequest(`/api/database/tables/${encodeURIComponent(table)}/rows/${id}`, { method: 'DELETE' })
      setIsLoading(true)
      setReloadVersion((version) => version + 1)
    } catch (deleteError) {
      setError(deleteError instanceof Error ? deleteError.message : 'No se pudo completar la operación.')
    }
  }

  if (!isAdmin) return <section className="w-full text-muted">Esta sección requiere permisos de administración.</section>

  return (
    <section className="w-full">
      <p className="mb-2 text-xs font-black tracking-[0.12em] text-red uppercase">Gestión provisional</p>
      <h1 className="m-0 text-4xl font-bold tracking-tight text-ink md:text-5xl">Datos de la escuela</h1>
      <p className="mt-4 max-w-3xl text-base leading-7 text-muted">Editor provisional de tablas permitidas. Las relaciones se eligen por nombre y el backend mantiene las restricciones de cada registro.</p>

      {tableListError ? (
        <div className="mt-5 rounded-soft bg-red/10 p-3 text-sm text-red-dark" role="alert">
          <p className="m-0 font-bold">{tableListError}</p>
          <button className="mt-2 font-bold underline" type="button" onClick={() => { setTableListError(null); setTableListVersion((version) => version + 1) }}>Reintentar</button>
        </div>
      ) : null}
      {isTableListLoading ? <p className="mt-5 text-sm text-muted">Cargando tablas…</p> : null}

      <div className="mt-7 flex flex-wrap gap-2">
        {tables.map((name) => <button key={name} className={`rounded-full px-4 py-2 text-sm font-bold ${table === name ? 'bg-red text-white' : 'border border-line bg-paper text-muted'}`} type="button" onClick={() => { setIsLoading(true); setError(null); setRows([]); setColumns([]); setReferencedTables({ owner: '', values: {} }); setEditingRow(null); setIsCreating(false); setTable(name) }}>{tableLabel(name)}</button>)}
      </div>

      {table ? (
        <>
          <div className="mt-5 flex flex-wrap items-center justify-between gap-4">
            <h2 className="m-0 text-2xl font-bold text-ink">{title}</h2>
             {!isAdministratorTable ? <button className="rounded-full bg-red px-4 py-2 text-sm font-bold text-white disabled:opacity-50" type="button" onClick={() => { setEditingRow(null); setIsCreating(true); setError(null) }} disabled={isLoading || !columns.length}>+ Añadir</button> : null}
          </div>
          {isAdministratorTable ? <p className="mt-3 text-sm text-muted">Hay una única cuenta ADMIN, gestionada por el equipo de desarrollo mediante el procedimiento seguro de alta.</p> : null}

          {error ? <p className="mt-4 rounded-soft bg-red/10 p-3 text-sm font-bold text-red-dark" role="alert">{error}</p> : null}
          {referenceError ? (
            <div className="mt-4 rounded-soft bg-gold/15 p-3 text-sm text-red-dark" role="status">
              <p className="m-0 font-bold">{referenceError}</p>
              <button className="mt-2 font-bold underline" type="button" onClick={() => { setReferenceError(null); setReloadVersion((version) => version + 1) }}>Reintentar relaciones</button>
            </div>
          ) : null}
          {!hasPrimaryKey ? <p className="mt-4 text-sm text-muted">Esta tabla no declara una clave primaria; se pueden consultar y añadir filas, pero no identificarlas para editarlas o borrarlas.</p> : null}

          {isCreating || editingRow ? (
            referenceOptionsLoading ? (
              <PanelCard className="mt-5 p-6"><p className="m-0 text-sm text-muted">Cargando opciones relacionadas…</p></PanelCard>
            ) : (
              <PanelCard className="mt-5 p-6">
                <h3 className="m-0 text-xl font-bold text-ink">{editingRow ? 'Editar registro' : 'Nuevo registro'}</h3>
                {table === 'administradores' && editingRow ? <p className="mt-2 text-sm text-muted">Los administradores no se pueden editar desde esta herramienta; crea o elimina registros según necesites.</p> : null}
                {referenceError ? <p className="mt-2 text-sm text-red-dark">No se han podido cargar las opciones de las relaciones; los campos relacionados quedan desactivados.</p> : null}
                <form className="mt-5 grid gap-4 md:grid-cols-2 xl:grid-cols-3" onSubmit={saveRow} key={editingRow ? rowId(editingRow, columns) : 'new-row'}>
                  {editableColumns.map((column) => {
                    const currentValue = editingRow?.[column.name]
                    const value = currentValue === null || currentValue === undefined ? '' : String(currentValue)
                  if (column.foreignKey) {
                    const relation = references[column.foreignKey.tableName]
                    const required = !column.nullable || (isCreating && ['cursos_agendados', 'horarios_recurrentes'].includes(table) && column.name === 'id_sala')
                    return (
                        <label key={column.name} className="grid gap-2 text-sm font-bold text-muted">
                          {column.name}
                          {relation ? (
                            <SelectField name={column.name} defaultValue={value} required={required}>
                              {column.nullable ? <option value="">Sin asignar</option> : null}
                              {relation.rows.map((option) => {
                                const optionValue = String(option[column.foreignKey!.columnName] ?? '')
                                return <option key={optionValue} value={optionValue}>{referenceLabel(option, column.foreignKey!, relation.columns)}</option>
                              })}
                            </SelectField>
                        ) : <SelectField disabled required={required}><option value="">Opciones no disponibles</option></SelectField>}
                        </label>
                      )
                    }
                    if (column.dataType === 'boolean') {
                      return <label key={column.name} className="flex items-center gap-3 text-sm font-bold text-muted"><input name={column.name} type="checkbox" defaultChecked={editingRow ? currentValue === true : currentValue !== false} />{column.name}</label>
                    }
                    const inputType = column.name === 'password_hash' ? 'password' : column.dataType === 'date' ? 'date' : column.dataType.includes('timestamp') ? 'datetime-local' : isNumber(column) ? 'number' : 'text'
                    const label = column.name === 'password_hash' ? 'Contraseña inicial' : column.name
                    const required = !column.nullable || (column.name === 'password_hash' && isCreating)
                    return <label key={column.name} className="grid gap-2 text-sm font-bold text-muted">{label}<input className={inputClass} name={column.name} type={inputType} defaultValue={value.slice(0, inputType === 'datetime-local' ? 16 : undefined)} required={required} /></label>
                  })}
                  <div className="flex flex-wrap gap-3 md:col-span-2 xl:col-span-3">
                    <button className="min-h-10 rounded-full bg-red px-5 text-sm font-bold text-white disabled:opacity-50" type="submit" disabled={isSaving || (editingRow !== null && table === 'administradores')}>{isSaving ? 'Guardando…' : 'Guardar'}</button>
                    <button className="min-h-10 rounded-full border border-line bg-paper px-5 text-sm font-bold text-muted" type="button" onClick={() => { setEditingRow(null); setIsCreating(false) }} disabled={isSaving}>Cancelar</button>
                  </div>
                </form>
              </PanelCard>
            )
          ) : null}

          <PanelCard className="mt-5 overflow-x-auto p-5">
            {isLoading ? <p className="text-muted">Cargando datos…</p> : (
              <table className="w-full min-w-[44rem] border-collapse text-left text-sm">
                <caption className="sr-only">Registros de {title}</caption>
                <thead><tr className="border-b border-line text-muted">{visibleColumns.map((column) => <th key={column.name} className="p-3 font-bold" scope="col">{column.name}</th>)}<th className="p-3" scope="col">Acciones</th></tr></thead>
                  <tbody>
                    {rows.map((row, index) => {
                      const rowLabel = visibleColumns.map((column) => formatValue(row[column.name])).join(' · ')
                      return (
                        <tr key={rowId(row, columns) || `${table}-${index}`} className="border-b border-line/70">
                          {visibleColumns.map((column) => <td key={column.name} className="max-w-56 truncate p-3 text-ink">{formatValue(row[column.name])}</td>)}
                          <td className="whitespace-nowrap p-3">
                            {table !== 'administradores' && hasPrimaryKey && !(['cursos_agendados', 'horarios_recurrentes'].includes(table) && row.activo === false)
                              ? <button className="mr-3 font-bold text-red-dark" type="button" aria-label={`Editar ${rowLabel}`} onClick={() => { setEditingRow(row); setIsCreating(false); setError(null) }}>Editar</button>
                              : null}
                            {hasPrimaryKey && !isAdministratorTable && !(['cursos_agendados', 'horarios_recurrentes'].includes(table) && row.activo === false)
                              ? <button className="font-bold text-red" type="button" aria-label={`${removalLabel(table)} ${rowLabel}`} onClick={() => void deleteRow(row)}>{removalLabel(table)}</button>
                              : ['cursos_agendados', 'horarios_recurrentes'].includes(table) && row.activo === false ? 'Cancelado' : 'Solo lectura'}
                          </td>
                        </tr>
                      )
                    })}
                  {!rows.length ? <tr><td className="p-3 text-muted" colSpan={visibleColumns.length + 1}>No hay registros en esta tabla.</td></tr> : null}
                </tbody>
              </table>
            )}
          </PanelCard>
          {foreignKeyTables.some((name) => references[name]?.rows.length === 500) ? <p className="mt-2 text-xs text-muted">Los selectores de relaciones muestran como máximo 500 opciones por tabla.</p> : null}
        </>
      ) : null}
    </section>
  )
}
