function tableLabel(table: string) {
  return tableLabels[table] ?? table.replaceAll('_', ' ').replace(/^\p{L}/u, (letter) => letter.toLocaleUpperCase('es-ES'))
}

function fieldLabel(column: Column) {
  if (friendlyFieldLabels[column.name]) return friendlyFieldLabels[column.name]
  if (column.foreignKey) {
    const labels: Record<string, string> = {
      alumno_forma: 'Relación alumno-forma',
      alumnos: 'Alumno',
      cursos: 'Curso',
      formas: 'Forma',
      grados: 'Grado',
      instructores: 'Instructor',
      personas: 'Persona',
      salas: 'Sala',
      estilos: 'Estilo',
    }
    return labels[column.foreignKey.tableName] ?? tableLabel(column.foreignKey.tableName)
  }
  return column.name.replace(/^id_/u, '').replaceAll('_', ' ').replace(/^\p{L}/u, (letter) => letter.toLocaleUpperCase('es-ES'))
}

function isNumber(column: Column) {
  return ['smallint', 'integer', 'bigint', 'real', 'double precision', 'numeric', 'decimal'].includes(column.dataType)
}

function formatValue(value: unknown) {
  if (value === null || value === undefined || value === '') return '—'
  if (typeof value === 'boolean') return value ? 'Sí' : 'No'
  return String(value)
}

function primaryKeyColumns(columns: Column[]) {
  return columns.filter((column) => column.primaryKey)
}

function rowId(row: Row, columns: Column[]) {
  return primaryKeyColumns(columns).map((column) => String(row[column.name])).join(',')
}

function referenceLabel(row: Row, reference: ForeignKey, columns: Column[]) {
  const value = row[reference.columnName]
  const labelColumn = columns.find((column) => column.name === 'nombre')
    ?? columns.find((column) => ['correo_electronico', 'numero_matricula', 'fecha_hora'].includes(column.name))
    ?? columns.find((column) => !column.primaryKey && column.name !== 'password_hash')
  const label = labelColumn ? formatValue(row[labelColumn.name]) : `ID ${formatValue(value)}`
  return labelColumn && labelColumn.name !== reference.columnName ? `${label} · ${formatValue(value)}` : label
}

function friendlyValue(row: Row, column: Column, references: Record<string, ReferencedTable>) {
  if (!column.foreignKey) return formatValue(row[column.name])
  const relation = references[column.foreignKey.tableName]
  const relatedRow = relation?.rows.find((candidate) => String(candidate[column.foreignKey!.columnName]) === String(row[column.name]))
  if (!relatedRow || !relation) return formatValue(row[column.name])
  const labelColumn = relation.columns.find((candidate) => candidate.name === 'nombre')
    ?? relation.columns.find((candidate) => ['correo_electronico', 'numero_matricula'].includes(candidate.name))
  return labelColumn ? formatValue(relatedRow[labelColumn.name]) : formatValue(row[column.name])
}

function friendlyTitle(row: Row, columns: Column[], references: Record<string, ReferencedTable>) {
  const titleColumn = columns.find((column) => ['nombre', 'nombre_forma', 'nombre_estilo', 'nombre_grado', 'correo_electronico', 'numero_matricula'].includes(column.name))
    ?? columns.find((column) => !column.primaryKey && !column.autoGenerated && column.name !== 'password_hash')
  return titleColumn ? friendlyValue(row, titleColumn, references) : 'Registro'
}

function removalLabel(table: string) {
  if (table === 'cursos_agendados') return 'Cancelar sesión'
  if (table === 'horarios_recurrentes') return 'Cancelar horario'
  if (table === 'salas') return 'Desactivar'
  return 'Eliminar'
}

